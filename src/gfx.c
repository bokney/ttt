void clear_bkg(void) {
    uint8_t blank_tile = 0;
    for (uint8_t y = 0; y < 32; y++) {
        for (uint8_t x = 0; x < 32; x++) {
            set_bkg_tiles(x, y, 1, 1, &blank_tile);
        }
    }
}

void fade_out(void) {
    fadeStage = 0;
    while (1) {
        switch(fadeStage) {
            case 0: BGP_REG = 0xE4; break;
            case 1: BGP_REG = 0x90; break;
            case 2: BGP_REG = 0x40; break;
            case 3: BGP_REG = 0x00; break;
        }
        fadeStage++;
        if (fadeStage == 4) break;
        delay(80);
        wait_vbl_done();
    }
}

void fade_in(void) {
    fadeStage = 0;
    while (1) {
        switch(fadeStage) {
            case 0: BGP_REG = 0x00; break;
            case 1: BGP_REG = 0x40; break;
            case 2: BGP_REG = 0x90; break;
            case 3: BGP_REG = 0xE4; break;
        }
        fadeStage++;
        if (fadeStage == 4) break;
        delay(80);
        wait_vbl_done();
    }
}
